#!/bin/bash
## Apply the configured AWS profile to the AgentCore CLI
#
# Declared as this feature's postStartCommand. It runs on every start, AFTER every
# feature's postCreateCommand: the skill copies below land in ~/.claude and ~/.pi,
# which the claude and pi features turn into volume symlinks at create, and a file
# written before that link replaced the directory would be deleted with it.
# Everything here is regenerated from the profile, so running it again is harmless.
#
# The CLI has no setting for a default model and resolves its Region from
# AWS_REGION, so the profile reaches it two ways:
#   - a wrapper at ~/.local/bin/agentcore (ahead of the npm bin on PATH) that sets
#     AWS_REGION and telemetry for this CLI only, when the fragment asks for either;
#   - an `agentcore` skill telling the coding agents which Region and Bedrock model
#     ids this account can use, since every create/add command takes them as flags.
set -euo pipefail

# .devcontainer/, two levels up from .devcontainer/features/agentcore/.
DEVCONTAINER_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
DEVENV="$DEVCONTAINER_DIR/devcontainer.env"
PROFILES_DIR="$DEVCONTAINER_DIR/profiles"
MARKER="Generated by .devcontainer/features/agentcore/poststart.sh"
WRAPPER="$HOME/.local/bin/agentcore"
SKILL_DIRS=()
command -v claude &>/dev/null && SKILL_DIRS+=("$HOME/.claude/skills/agentcore")
command -v pi &>/dev/null && SKILL_DIRS+=("$HOME/.pi/agent/skills/agentcore")
# Codex and OpenCode read ~/.agents/skills directly.
if command -v codex &>/dev/null || command -v opencode &>/dev/null; then
    SKILL_DIRS+=("$HOME/.agents/skills/agentcore")
fi

# --- Select the profile ---
# The CUI partition keeps aws and awsgov from both being configured, so at most one
# fragment normally applies; with more, the first wins and the rest are named.
PROFILE=""
if [ -f "$DEVENV" ]; then
    PROFILES_LINE=$(grep '^CONFIGURED_PROFILES=' "$DEVENV" 2>/dev/null || true)
    CSV="${PROFILES_LINE#CONFIGURED_PROFILES=}"
    # Strip CR: setup.ps1 writes CRLF and this reads the file directly (see
    # features/chat/postcreate.sh).
    CSV="${CSV//$'\r'/}"
    IFS=',' read -ra CONFIGURED <<< "$CSV"
    for p in "${CONFIGURED[@]}"; do
        [ -f "$PROFILES_DIR/$p/agentcore.json" ] || continue
        if [ -z "$PROFILE" ]; then
            PROFILE="$p"
        else
            echo -e "\e[33m⚠️  AgentCore: using profile '$PROFILE'; ignoring '$p'.\e[0m"
        fi
    done
fi

# Remove only what this script generated, never a user's own file.
remove_generated() {
    if [ -f "$WRAPPER" ] && grep -qF "$MARKER" "$WRAPPER"; then
        rm -f "$WRAPPER"
    fi
    for d in "$HOME/.claude/skills/agentcore" "$HOME/.pi/agent/skills/agentcore" \
             "$HOME/.agents/skills/agentcore"; do
        if [ -f "$d/SKILL.md" ] && grep -qF "$MARKER" "$d/SKILL.md"; then
            rm -rf "$d"
        fi
    done
}

remove_generated
[ -n "$PROFILE" ] || exit 0

FRAGMENT="$PROFILES_DIR/$PROFILE/agentcore.json"
REGION=$(jq -r '.region // empty' "$FRAGMENT")
TELEMETRY=$(jq -r 'if .telemetry == false then "off" else "on" end' "$FRAGMENT")
DEFAULT_MODEL=$(jq -r '.defaultModel // empty' "$FRAGMENT")
# The agents' own Region, from the profile, for the skill text.
AGENT_REGION=$(grep '^AWS_REGION=' "$PROFILES_DIR/$PROFILE/profile.env" 2>/dev/null \
    | head -n 1 | cut -d= -f2 | tr -d '\r' || true)
CLI_REGION="${REGION:-$AGENT_REGION}"

# --- Wrapper ---
# Scans PATH for the next agentcore that is not this file, so a Node upgrade or
# `agentcore update` needs no regeneration. --region still beats AWS_REGION.
if [ -n "$REGION" ] || [ "$TELEMETRY" = "off" ]; then
    mkdir -p "$(dirname "$WRAPPER")"
    {
        echo '#!/bin/bash'
        echo "# $MARKER"
        echo "# from profiles/$PROFILE/agentcore.json; edit that file, not this one."
        if [ -n "$REGION" ]; then
            echo "export AWS_REGION=\"\${AGENTCORE_REGION:-$REGION}\""
        fi
        if [ "$TELEMETRY" = "off" ]; then
            echo 'export AGENTCORE_TELEMETRY_DISABLED=1'
        fi
        cat <<'EOF'
self="$(readlink -f "$0")"
IFS=: read -ra dirs <<< "$PATH"
for d in "${dirs[@]}"; do
    if [ -x "$d/agentcore" ] && [ "$(readlink -f "$d/agentcore")" != "$self" ]; then
        exec "$d/agentcore" "$@"
    fi
done
echo "agentcore: the AgentCore CLI is not installed (npm install -g @aws/agentcore)" >&2
exit 127
EOF
    } > "$WRAPPER"
    chmod +x "$WRAPPER"
fi

# --- Skill ---
[ ${#SKILL_DIRS[@]} -gt 0 ] || exit 0

MODELS=""
if [ -f "$PROFILES_DIR/$PROFILE/models.json" ]; then
    MODELS=$(jq -r '.providers[]?.models[]? | "- `\(.id)` — \(.name)"' \
        "$PROFILES_DIR/$PROFILE/models.json")
fi

REGION_NOTE="Commands use \`AWS_REGION\` (\`$CLI_REGION\`)."
if [ -n "$REGION" ] && [ "$REGION" != "$AGENT_REGION" ]; then
    REGION_NOTE="The \`agentcore\` wrapper on PATH sets it for this CLI
  only; the other agents keep \`$AGENT_REGION\`. Override with \`--region\` or
  \`AGENTCORE_REGION\`."
fi

TELEMETRY_NOTE="on (upstream default; \`agentcore config telemetry.enabled false\` opts out)."
if [ "$TELEMETRY" = "off" ]; then
    TELEMETRY_NOTE="off (set by the profile; the wrapper exports AGENTCORE_TELEMETRY_DISABLED=1)."
fi

LIMITS=""
case "$CLI_REGION" in
    us-gov-*)
        LIMITS="- GovCloud: AgentCore runs only in \`us-gov-west-1\`, which has harness,
  Runtime (microVM), Memory, Gateway, Identity, built-in tools, Observability,
  Policy, and Evaluations. Payments, optimization, Runtime Instances, and Agent
  Registry are not available there.
- Each model must be entitled in the deployment Region. \`features/bedrock\` requests
  the entitlement on create; if an invoke fails with an access error, rebuild or run
  \`.devcontainer/scripts/enable-govcloud-models.sh\`.
"
        ;;
esac

SKILL=$(cat <<EOF
---
name: agentcore
description: Use before running the AgentCore CLI (agentcore) to create, deploy, or invoke Amazon Bedrock AgentCore harnesses and runtimes in this container. Gives this project's deployment Region, the Bedrock model IDs its AWS account can use, and what the container cannot build.
---

<!-- $MARKER from profiles/$PROFILE/agentcore.json. Edit that file, not this one. -->

# AgentCore CLI (profile: $PROFILE)

- Region: \`$CLI_REGION\`. $REGION_NOTE
- Telemetry: $TELEMETRY_NOTE
- Pass flags and \`--json\` for non-interactive runs; a command run without flags
  opens the TUI. \`agentcore <command> --help\` lists every flag.

## Models

The CLI's built-in default model is not this profile's. Always choose one:

- Harness: \`agentcore add harness --name NAME --model '{"bedrockModelConfig":{"modelId":"$DEFAULT_MODEL"}}'\`
- Runtime templates: \`agentcore create --template ...\` scaffolds the CLI default
  model id into the generated code (\`model/load.py\` or \`model/load.ts\`); replace it
  with an id below. Interactive \`agentcore create\` asks for the provider and id.
- LLM-as-a-judge evaluators: \`--model <id>\`.

Default: \`$DEFAULT_MODEL\`. Bedrock IDs configured for this profile:

$MODELS

## Limits

${LIMITS}- No container engine here: \`*-container\` templates, \`--dockerfile\`, and runtimes
  with a Dockerfile cannot build locally. Use the default CodeZip build.
- Deployed agents run in AWS: they cannot reach this container's LiteLLM proxy
  (127.0.0.1) or the SEI providers. Use Bedrock models.
EOF
)

for d in "${SKILL_DIRS[@]}"; do
    mkdir -p "$d"
    printf '%s\n' "$SKILL" > "$d/SKILL.md"
done
